def glyph_mask(char, size=(64,96)):
    """Stable high-resolution master; letter O and digit 0 intentionally share shape."""
    w,h=size; ss=4
    mask=Image.new('L',(w*ss,h*ss)); draw=ImageDraw.Draw(mask)
    # Same narrow stroke in both axes; leave a complete ink margin.
    stroke=7*ss
    for path in PATHS[char]:
        points=[((7+x/80*50)*w/64*ss,(6+y/100*84)*h/96*ss) for x,y in path]
        draw.line(points,fill=255,width=stroke,joint='curve')
    return mask.resize(size,Image.Resampling.LANCZOS)
